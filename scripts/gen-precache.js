#!/usr/bin/env node
/**
 * Regenerates the service worker's precache list from what is actually on disk.
 *
 * The list was hand-maintained until a refactor moved three modules out of src/tank/ and into
 * src/lib/. Nothing broke visibly — precache entries are added individually so a 404 degrades
 * instead of aborting the install — it just left three holes in the offline app. The invariant
 * test caught it, but a list that needs a test to stay correct is a list that should be
 * generated.
 *
 * Run: node scripts/gen-precache.js  (wired into `npm run bust`, before the token stamp)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SW = join(ROOT, 'sw.js');

const BEGIN = '// <precache:begin> generated by scripts/gen-precache.js — do not edit by hand';
const END = '// <precache:end>';

function walk(dir, filter) {
  const out = [];
  let entries;
  try { entries = readdirSync(dir); } catch { return out; }
  for (const entry of entries) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full, filter));
    else if (filter(full)) out.push(full);
  }
  return out;
}

const web = (abs, base = ROOT) => '/' + relative(base, abs).split('\\').join('/');
const js = (f) => f.endsWith('.js');

// Fingerprinted entries need the token interpolated at runtime, so they are emitted as
// template literals. Everything else is a plain string.
const fingerprinted = ['/styles.css', '/src/main.js', '/cb-badge.js'];

const urls = [
  '/',
  '/index.html',
  '/offline.html',
  '/manifest.webmanifest',
  ...fingerprinted,
  ...walk(join(ROOT, 'src'), js).map((f) => web(f)),
  ...walk(join(ROOT, 'vendor', 'three'), js).map((f) => web(f)),
  ...walk(join(ROOT, 'public', 'icons'), (f) => f.endsWith('.png'))
    .map((f) => web(f, join(ROOT, 'public'))),
];

const seen = new Set();
const lines = [];
for (const url of urls) {
  if (seen.has(url)) continue;
  seen.add(url);
  lines.push(fingerprinted.includes(url)
    ? '  `' + url + '?v=${CB_TOKEN}`,'
    : `  '${url}',`);
}

const src = readFileSync(SW, 'utf8');
const a = src.indexOf(BEGIN);
const b = src.indexOf(END);
if (a < 0 || b < 0) {
  console.error('sw.js is missing the precache markers; not touching it');
  process.exit(1);
}

const next = src.slice(0, a + BEGIN.length) + '\n' + lines.join('\n') + '\n' + src.slice(b);
writeFileSync(SW, next);
console.log(`precache: ${lines.length} entries`);
